const fs=require('fs');
const vm=require('vm');
const assert=require('assert');
const root=process.cwd();
const content=fs.readFileSync(root+'/aspt/content.js','utf8');
const exam=fs.readFileSync(root+'/aspt/exam.js','utf8');
const css=fs.readFileSync(root+'/aspt/exam.css','utf8');
const sandbox={}; vm.runInNewContext(content+';this.data=ASPT_DATA;',sandbox);
const d=sandbox.data, qs=d.section19Questions||[], cards=d.section19Flashcards||[], matrix=JSON.parse(fs.readFileSync(root+'/aspt/section19-coverage.json','utf8'));
assert.equal(d.section19OriginalQuestionCount,21,'original Section 19 count changed');
assert.equal(qs.length,52,'expected 52 Section 19 questions');
assert.equal(matrix.inventory.currentQuestionCount,qs.length,'coverage count drift');
assert.equal(matrix.inventory.addedQuestionCount,31,'net-added count drift');
assert.equal(new Set(qs.map(q=>q.id)).size,qs.length,'duplicate question ids');
const levels={1:0,2:0,3:0,4:0};
for(const q of qs){
  assert(/^s19-\d{3}$/.test(q.id),'bad id '+q.id);
  assert([1,2,3,4].includes(q.level),'bad level '+q.id); levels[q.level]++;
  assert(q.category&&q.concept,'missing concept metadata '+q.id);
  assert(Array.isArray(q.sourceRefs)&&q.sourceRefs.length,'missing sources '+q.id);
  assert(Array.isArray(q.o)&&q.o.length===4,'need four options '+q.id);
  assert.equal(new Set(q.o).size,4,'duplicate option '+q.id);
  assert(Number.isInteger(q.a)&&q.a>=0&&q.a<q.o.length,'bad answer '+q.id);
  assert(Array.isArray(q.wrong)&&q.wrong.length===q.o.length,'missing distractor rationales '+q.id);
  q.o.forEach((_,i)=>{if(i!==q.a)assert(q.wrong[i]&&q.wrong[i].trim(),'missing wrong-answer rationale '+q.id+' option '+i);});
  assert(q.e&&q.e.length>20,'weak explanation '+q.id);
  assert(!q.sourceRefs.some(ref=>ref==='Chapters 05–10'),'blanket source range '+q.id);
  assert(!q.o.some(opt=>/AV junction is absent|solely because|completely absent ventricular activity/i.test(opt)),'reviewed-out distractor returned '+q.id);
}
assert(levels[2]+levels[3]+levels[4]>levels[1]*8,'Level 1 dominates');
assert(qs.filter(q=>q.level>=3).length>=24,'hard pool too small');
const imageFields=['d','img','dimg','diagramId'];
const imageDependent=qs.filter(q=>imageFields.some(field=>q[field]));
assert.equal(imageDependent.length,0,'Section 19 image-dependent questions remain: '+imageDependent.map(q=>q.id).join(', '));
const visualDirections=/\b(?:inspect|view|compare)\b[^.?!]*(?:strip|waveform|image|diagram)|\b(?:teaching strip|schematic teaching|shown (?:above|below)|which strip)\b/i;
for(const q of qs)assert(!visualDirections.test(q.q),'Section 19 visual-dependent wording remains '+q.id);
assert(exam.includes("q.level>=3"),'hard mode level gate missing');
assert(!exam.includes("length>=10"),'retired hard-mode visual target remains');
const grouped=[...new Set(qs.map(q=>q.attemptGroup).filter(Boolean))];
assert(grouped.length>=5,'too few near-duplicate concept families tracked');
for(const name of grouped)assert(qs.filter(q=>q.attemptGroup===name).length>=2,'single-item attempt group '+name);
assert(exam.includes("usedGroups")&&exam.includes("q.attemptGroup"),'concept-family suppression missing');
assert(exam.includes("new Set(pool.map(q=>q.category))"),'category balancing missing');
assert(exam.includes("Math.random()*wordings.length"),'wording randomization missing');
assert(exam.includes("practice-hard"),'hard mode action missing');
assert(cards.length>=12,'too few Section 19 flashcards');
for(const card of cards)assert(card.front&&card.back&&card.sourceRefs?.length,'invalid flashcard');
const coveredIds=new Set(matrix.coverage.flatMap(row=>row.questionIds));
for(const q of qs)assert(coveredIds.has(q.id),'question absent from coverage matrix '+q.id);
assert(matrix.coverage.some(row=>row.status==='limited / flagged'&&/AGONAL/.test(row.concept)),'agonal warning absent');
for(const id of ['s19-034','s19-035'])assert(/working|inferred|association/i.test(qs.find(q=>q.id===id).e),'agonal overstatement '+id);
assert.equal(matrix.inventory.visualQuestionCount,0,'coverage visual count drift');
assert.equal(matrix.inventory.rewrittenImageDependentQuestionCount,13,'rewritten image-dependent count drift');
assert.equal(matrix.visuals.length,0,'retired coverage visuals remain');
assert.equal(matrix.formatPolicy?.retiredImageDependentQuestionCount,13,'format-policy count drift');
assert(!/const s19Svg|s19_rr_irregular|SCHEMATIC TEACHING DIAGRAM/.test(exam),'retired Section 19 SVG generator remains');
assert(!/\.s19-wave\{/.test(css),'retired Section 19 waveform style remains');
assert(/@media\(max-width:620px\)/.test(css),'Section 19 mobile CSS missing');
console.log(JSON.stringify({questions:qs.length,levels,imageDependent:imageDependent.length,rewrittenTextQuestions:matrix.inventory.rewrittenImageDependentQuestionCount,flashcards:cards.length,categories:new Set(qs.map(q=>q.category)).size,coverageRows:matrix.coverage.length},null,2));
