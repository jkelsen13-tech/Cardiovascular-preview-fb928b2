  await page.waitForFunction(()=>document.querySelector('#ecg3DStatus')?.textContent.includes('became unavailable'));
  assert(await page.locator('.ecg-heart-svg').isVisible());
  assert(await page.locator('#ecgStageSlider').isVisible(),'context loss must restore the shared slider');
