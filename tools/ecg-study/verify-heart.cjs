  assert.equal(await page.locator('.ecg-3d-canvas').evaluate(el=>getComputedStyle(el).touchAction),'none');
  await page.locator('[data-action="touch"]').click();
  assert.equal(await page.locator('.ecg-3d-canvas').evaluate(el=>getComputedStyle(el).touchAction),'pan-y');
